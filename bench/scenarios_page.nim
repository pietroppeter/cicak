## Renders bench/scenarios.html: every scenario's cells, as the benchmark adds them.
##
##   nim r bench/scenarios_page.nim

import std/[os, json, strutils, strformat, algorithm, sequtils]
import nimib
import ../docs/theme
import scenario

let benchDir = currentSourcePath().parentDir

# s0's length as run: from the latest run that has it, else the harness default
var s0cells = 100
var runs: seq[string]
for kind, d in walkDir(benchDir / "results"):
  if kind == pcDir and fileExists(d / "meta.json"): runs.add d
runs.sort
for d in runs:
  let m = parseFile(d / "meta.json")
  if m["scenarios"].hasKey("s0"): s0cells = m["scenarios"]["s0"]["cells"].getInt

var all = @[scenario0(s0cells)]
var files: seq[string]
for f in walkFiles(benchDir / "scenarios" / "*.nim"): files.add f
files.sort
for f in files: all.add loadScenario(f)
all.add calibration()

proc source(sc: Scenario): string =
  case sc.id
  of "s0", "cal": "generated by [scenario.nim](https://github.com/pietroppeter/cicak/blob/main/bench/scenario.nim)"
  else:
    for f in files:
      if f.extractFilename.startsWith(sc.id & "_"):
        return &"[scenarios/{f.extractFilename}](https://github.com/pietroppeter/cicak/blob/main/bench/scenarios/{f.extractFilename})"
    ""

nbInit
nb.title = "cicak benchmark: scenarios"
nb.doc.filename = benchDir / "scenarios.html"
nb.useTheme(
  titleHtml = "Benchmark <em>scenarios</em>",
  eyebrow = "cicak benchmark",
  epigraph = "Every cell of every scenario, in the order the benchmark adds them.",
  meta = "source: bench/scenarios and bench/scenario.nim",
  summary = "The cells of the cicak benchmark scenarios.",
)

var intro = """
The [results](results.html) and the [design doc](design.html) refer to these scenarios.
Each cell becomes a module `cell_<k>.nim` that starts with `import cell_1` … `import cell_<k-1>`
(left out below), so a cell sees what earlier cells export with `*`. Modules imported by an
earlier cell are not visible unless it re-exports them (`export`), which is why cell 1 of
s1 to s3 imports and re-exports what the later cells use.

| id | scenario | cells |
|---|---|---|
"""
for sc in all:
  intro.add &"| [{sc.id}](#{sc.id}) | {sc.title} | {sc.cells.len} |\n"
nbText: intro

for sc in all:
  var text = &"<h2 id=\"{sc.id}\">{sc.id}: {sc.title}</h2>\n\n{sc.description}\n\nSource: {sc.source}."
  if sc.paths.len > 0:
    text.add " Dependencies (cloned by `bench/deps.sh`, passed as `--path:`): " & sc.paths.mapIt("`" & it.replace("deps/", "") & "`").join(", ") & "."
  nbText: text
  var code = ""
  for i, (title, body) in sc.cells:
    if i > 0: code.add "\n\n"
    code.add &"# %% {i + 1}. {title}\n{body}"
  nbText: "```nim\n" & code & "\n```"

nbSave

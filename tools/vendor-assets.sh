#!/usr/bin/env bash
# Vendors the pages' third-party assets into docs/assets, so no page loads anything
# from a CDN: highlight.js (shell snippets), plotly.js (benchmark charts) and the
# theme's fonts (latin and latin-ext subsets). Packages come from npm; re-run to
# update after changing a version below. Needs npm, tar and python3.
set -euo pipefail

HLJS=11.9.0
PLOTLY=2.35.2
FONTSOURCE=5.3.0

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/docs/assets"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

fetch() {  # fetch <package@version> <dir>: unpacks the npm package into $tmp/<dir>
  mkdir -p "$tmp/$2"
  (cd "$tmp" && npm pack -q "$1" > "$2.name" 2>/dev/null)
  tar xzf "$tmp/$(tail -1 "$tmp/$2.name")" -C "$tmp/$2" --strip-components 1
}
fetch "@highlightjs/cdn-assets@$HLJS" hljs
fetch "plotly.js-dist-min@$PLOTLY" plotly
fetch "@fontsource/familjen-grotesk@$FONTSOURCE" familjen
fetch "@fontsource-variable/literata@$FONTSOURCE" literata
fetch "@fontsource/jetbrains-mono@$FONTSOURCE" jetbrains

rm -rf "$out" && mkdir -p "$out/hljs" "$out/plotly" "$out/fonts"
cp "$tmp/hljs/highlight.min.js" "$tmp/hljs/languages/bash.min.js" "$tmp/hljs/LICENSE" "$out/hljs/"
cp "$tmp/plotly/plotly.min.js" "$out/plotly/plotly-$PLOTLY.min.js"
cp "$tmp/plotly/LICENSE" "$out/plotly/"

# fonts.css: the @font-face rules of the faces the theme uses, latin and latin-ext only,
# woff2 only, pointing at fonts/<file>; Literata keeps its optical-size axis
python3 - "$tmp" "$out" <<'PY'
import re, shutil, sys, pathlib
tmp, out = map(pathlib.Path, sys.argv[1:])
faces = [  # (package dir, css files, family name used by the theme)
    ("familjen", ["500.css", "700.css"], "Familjen Grotesk"),
    ("literata", ["opsz.css", "opsz-italic.css"], "Literata"),
    ("jetbrains", ["400.css", "600.css"], "JetBrains Mono"),
]
css = ["/* Generated by tools/vendor-assets.sh from Fontsource (SIL Open Font License 1.1). */\n"]
for pkg, files, family in faces:
    for f in files:
        for block in re.findall(r"@font-face \{.*?\}", (tmp / pkg / f).read_text(), re.S):
            m = re.search(r"url\(\./files/([a-z0-9-]+-latin(?:-ext)?-[a-z0-9]+-(?:normal|italic)\.woff2)\)", block)
            if not m:
                continue  # other subsets
            name = m.group(1)
            shutil.copy(tmp / pkg / "files" / name, out / "fonts" / name)
            block = re.sub(r"src: [^;]*;", f"src: url(fonts/{name}) format('woff2');", block)
            block = re.sub(r"font-family: '[^']*';", f"font-family: '{family}';", block)
            css.append(block + "\n")
    shutil.copy(tmp / pkg / "LICENSE", out / "fonts" / f"LICENSE-{pkg}")
(out / "fonts.css").write_text("\n".join(css))
PY
du -sh "$out"/*
